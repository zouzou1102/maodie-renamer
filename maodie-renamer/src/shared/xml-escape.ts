/**
 * OOXML 文本转义 —— xlsx 与 docx **共用一份**。
 *
 * ── 为什么抽成独立文件 ────────────────────────────────────────────────
 * 与 §5.⑦「两个写入器共用一个 ZIP 打包器」是同一个道理：
 * 抄两遍的话，「单引号要不要转」这种细节迟早会在其中一份里漂移，
 * 而错的那一份只会表现为「打开文件时某个文件名少了个字符」——
 * 既不会崩、也不会报错，极难发现。
 *
 * ── ★ 替换顺序 ────────────────────────────────────────────────────────
 * `&` 必须**第一个**替换。若先替换 `<` → `&lt;`，再替换 `&`，
 * 那么刚插进去的 `&lt;` 会被二次转义成 `&amp;lt;`，文件里就多出四个字符。
 * 这种错**只在列表里真有 `<` 时才出现**，平时测不出来。
 *
 * ── 不处理的两种情况（刻意的）─────────────────────────────────────────
 * · **控制字符**（0x00–0x08 等）：XML 1.0 不允许，但 Windows 文件名本来就
 *   不能含它们（`E_INVALID_CHAR` 已挡）。不做不可能发生的场景的处理。
 * · **emoji / 增补平面字符**：XML 1.0 **允许**，直接原样输出即可（有单测覆盖）。
 */

/** 转义 XML 文本节点的五个预定义实体 */
export function xmlEscape(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}
